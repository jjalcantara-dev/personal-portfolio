// Builds lib/games/library.ts: 60 "Desbloquea" and 60 "Puentes" levels, every
// one checked to have a single solution (see slide.mjs and bridges.mjs).
//
//   npm run puzzles
//
// Deterministic: fixed seeds and a fixed amount of work per worker, so the same
// code always produces the same library. Takes several minutes (it uses every
// CPU core); the result is committed, nothing runs at build time.

import { Worker, isMainThread, parentPort, workerData } from "node:worker_threads";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { availableParallelism } from "node:os";
import { fileURLToPath } from "node:url";
import * as slide from "./slide.mjs";
import * as bridges from "./bridges.mjs";

const PER_KIND = 60;
const SLIDE = { minMoves: 15, triesPerWorker: 8000 };
const BRIDGES = { W: 9, H: 9, islands: [24, 30], minGuesses: 5, triesPerWorker: 150000 };
const WORKERS = Math.max(1, availableParallelism() - 1);

if (!isMainThread) {
  const { kind, seed } = workerData;
  const out =
    kind === "slide"
      ? slide.generate({ count: Infinity, minMoves: SLIDE.minMoves, seed, maxTries: SLIDE.triesPerWorker })
      : bridges.generate({ count: Infinity, ...BRIDGES, seed, maxTries: BRIDGES.triesPerWorker });
  parentPort.postMessage(out);
} else {
  // Candidates are cached per kind (scripts/puzzles/.pool-*.json, git-ignored)
  // so a failed or tweaked run doesn't redo the slow part. --fresh ignores it.
  const fresh = process.argv.includes("--fresh");
  const run = async (kind) => {
    const cache = new URL(`./.pool-${kind}.json`, import.meta.url);
    if (!fresh && existsSync(cache)) {
      console.log(`${kind}: using cached candidates (--fresh to regenerate)`);
      return JSON.parse(readFileSync(cache, "utf8"));
    }
    const all = await runWorkers(kind);
    writeFileSync(cache, JSON.stringify(all));
    return all;
  };
  const runWorkers = (kind) =>
    Promise.all(
      Array.from({ length: WORKERS }, (_, i) =>
        new Promise((resolve, reject) => {
          const w = new Worker(fileURLToPath(import.meta.url), { workerData: { kind, seed: 1000 * (kind === "slide" ? 1 : 2) + i } });
          w.on("message", resolve);
          w.on("error", reject);
        }),
      ),
    ).then((parts) => parts.flat());

  const t0 = Date.now();
  console.log(`Generating on ${WORKERS} workers...`);

  const slideAll = await run("slide");
  const seen = new Set();
  const slideLevels = slideAll
    .filter((p) => {
      const sig = p.blocks.map((b) => `${b.h ? "h" : "v"}${b.len}${b.fixed}:${b.pos}`).sort().join("|");
      return !seen.has(sig) && seen.add(sig);
    })
    .sort((a, b) => b.minMoves - a.minMoves)
    .slice(0, PER_KIND);
  console.log(`slide: ${slideAll.length} candidates, kept ${slideLevels.length} (${slideLevels.at(-1)?.minMoves}-${slideLevels[0]?.minMoves} moves) after ${((Date.now() - t0) / 1000).toFixed(0)}s`);

  const bridgeAll = await run("bridges");
  const bridgeLevels = bridgeAll.sort((a, b) => b.guesses - a.guesses || b.islands.length - a.islands.length).slice(0, PER_KIND);
  console.log(`bridges: ${bridgeAll.length} candidates, kept ${bridgeLevels.length} after ${((Date.now() - t0) / 1000).toFixed(0)}s`);

  if (slideLevels.length < PER_KIND || bridgeLevels.length < PER_KIND) {
    console.error("Not enough levels: raise triesPerWorker.");
    process.exit(1);
  }

  // Shuffle deterministically so difficulty is spread over the days.
  const shuffle = (arr, seed) => {
    const r = slide.rng(seed);
    for (let i = arr.length - 1; i > 0; i--) {
      const j = Math.floor(r() * (i + 1));
      [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    return arr;
  };

  const slideOut = shuffle(slideLevels, 1).map((p, i) => ({
    id: `slide-${String(i + 1).padStart(3, "0")}`,
    minMoves: p.minMoves,
    blocks: p.blocks.map((b) => [b.h ? 1 : 0, b.len, b.fixed, b.pos]),
  }));
  const bridgeOut = shuffle(bridgeLevels, 2).map((p, i) => ({
    id: `bridges-${String(i + 1).padStart(3, "0")}`,
    width: p.W,
    height: p.H,
    islands: p.islands.map((s) => [s.x, s.y, s.n]),
  }));

  const ts = `// GENERATED by scripts/puzzles/generate.mjs (npm run puzzles). Do not edit by hand.
//
// Every level has exactly one solution:
// - slide: one shortest solution, up to the order of independent moves.
//   blocks: [horizontal (1|0), length, fixed row/column, position]; block 0 is
//   the red one, minMoves is the optimal number of moves.
// - bridges: one way to place the bridges. islands: [x, y, bridges needed].

import type { SlideLevel, BridgesLevel } from "./types";

export const slideLevels: SlideLevel[] = ${JSON.stringify(slideOut)};

export const bridgesLevels: BridgesLevel[] = ${JSON.stringify(bridgeOut)};
`;
  writeFileSync(new URL("../../lib/games/library.ts", import.meta.url), ts);
  console.log(`Wrote lib/games/library.ts in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
}
